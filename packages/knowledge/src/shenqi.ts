export function shenqiReading(heaven: string, earth: string, column: number): CombinationReading {
  const id = `${heaven}-${earth}`;
  const notes = [
    '默认依《神奇之门》中篇第五章第一节的公开网页转录；verified 只表示此转录已核，不代表纸本校勘或结果验证。',
    OCR_NOTES[id] ?? '',
    id === '庚-丙' ? '网页首处作“太白人荧”，但同条后句明确写“太白入荧”，据同条统一入字。' : '',
    id === '丙-辛'
      ? '网页没有另列独立格名；“谋事能成”为该条所用语句，此处作为摘要标签，不冒称专名。'
      : '',
    id === '丁-壬' ? '网页没有以“名为”另列格名；“贵人恩诏”为该条中的摘要标签，不冒称专名。' : '',
    id === '己-乙' ? '同条并列“墓神不明”“地户逢星”，同时保留。' : '',
    id === '庚-庚' ? '同条同时写“太白同宫”与“战格”，同时保留。' : '',
    id === '丙-戊'
      ? '本网页写“鸟跌穴”；《御定奇门宝鉴·混合百神》对照条写“飞鸟跌穴”，两条分别保留。'
      : '',
    '含“墓”“刑”“伏吟”的传统格名与本项目落宫辅助参数分别计算，不由格名字面触发标记。',
  ]
    .filter(Boolean)
    .join(' ');
  return {
    sourceId: 'shenqi-patterns',
    name: NAMES[heaven]![column]!,
    nameKind: id === '丙-辛' || id === '丁-壬' ? 'editorial' : 'named',
    summary: SUMMARIES[heaven]![column]!,
    conditions: [
      '按同一宫天盘干加地盘干读取，前后方向不可互换。',
      '这是《神奇之门》这一来源的名称和原创研习简释，需结合所问事项、门星及现实条件。',
      ...(id === '丁-乙' ? ['本条人遁名称不单独证明门、奇、神构成的复合人遁已成立。'] : []),
      ...(heaven === earth ? ['本宫同干不单独证明全盘伏吟。'] : []),
      ...(OCR_NOTES[id] ? ['格名存在转录疑字，暂不输出确定事件解释。'] : []),
    ],
    status: OCR_NOTES[id] ? 'pending' : 'verified',
    locator: `中篇第五章·第一节十干克应·${SECTION[heaven]}组·${heaven}加${earth}条`,
    note: notes,
  };
}
